import fs from 'node:fs/promises';
import { createRequire } from 'node:module';
import postcss from 'postcss';
import prefixer from 'postcss-prefix-selector';
const require = createRequire(import.meta.url);
// Keep library resets inside their own shells, even after a viewport change.
async function scope(source, target, prefix) {
  const css = await fs.readFile(source, 'utf8');
  const result = await postcss([prefixer({ prefix, transform(_prefix, selector) {
    let value = selector.replace(/(^|[\s>+~])(html|body|:root)(?=[\s.:#[>+~]|$)/g, `$1${prefix}`);
    value = value.replace(/^(\.md|\.ios)(?=[\s.:#[>+~]|$)/, `${prefix}$1`);
    if (value.startsWith(prefix)) return value;
    return `${prefix} ${value}`;
  } })]).process(css, { from: source, to: target });
  await fs.writeFile(target, `/* Generated by npm run styles:scope. */\n${result.css}`);
}
await scope(require.resolve('framework7/css/bundle'), 'src/styles/framework7-scoped.css', '.krug-mobile');
await scope('src/styles/studio-source.css', 'src/styles/studio-scoped.css', '.studio-scope');
